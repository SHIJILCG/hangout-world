import { beforeAll,afterAll,beforeEach,describe,it,expect } from 'vitest';
import { boot,type ColyseusTestServer } from '@colyseus/testing';
import appConfig from '../src/app.config';
import { HORSE, CART, riderPose } from '../../shared/rides';

describe('horse multiplayer contract',()=>{
  let server:ColyseusTestServer;
  beforeAll(async()=>{server=await boot(appConfig,2572);});
  afterAll(async()=>{await server?.shutdown();});
  beforeEach(async()=>{await server.cleanup();});
  it('replicates a cart driver independently from the horse and releases the seat on leave',async()=>{
    const room=await server.createRoom('world',{});
    const a=await server.connectTo(room,{name:'Driver'}),b=await server.connectTo(room,{name:'Rider'});
    a.onMessage('ride-result',()=>{});b.onMessage('ride-result',()=>{});
    const cart=room.state.rides.get(CART.id)!,horse=room.state.rides.get(HORSE.id)!;
    Object.assign(room.state.players.get(a.sessionId)!,{x:cart.x+2,y:cart.y,z:cart.z});
    Object.assign(room.state.players.get(b.sessionId)!,{x:horse.x+1.5,y:horse.y,z:horse.z});
    a.send('ride-action',{action:'mount',rideId:CART.id});b.send('ride-action',{action:'mount'});
    await expect.poll(()=>cart.occupant).toBe(a.sessionId);await expect.poll(()=>horse.occupant).toBe(b.sessionId);
    a.send('ride-input',{seq:1,dirX:0,dirZ:1,run:true});await expect.poll(()=>cart.z).toBeGreaterThan(CART.z);
    await room.waitForNextPatch();expect(b.state.cartsVersion).toBe(1);
    expect(b.state.rides.get(CART.id).occupant).toBe(a.sessionId);
    const pose=riderPose(cart,CART),driver=room.state.players.get(a.sessionId)!;
    expect(driver.x).toBeCloseTo(pose.x);expect(driver.z).toBeCloseTo(pose.z);expect(driver.y).toBeCloseTo(pose.y);
    expect(horse.z).toBe(HORSE.z);
    const token=a.reconnectionToken;await a.leave(false);await expect.poll(()=>cart.speed).toBe(0);
    expect(cart.occupant).toBe(a.sessionId);const restored=await server.sdk.reconnect(token);
    await room.waitForNextPatch();expect(restored.state.players.get(a.sessionId).rideId).toBe(CART.id);
    await restored.leave(true);await expect.poll(()=>cart.occupant).toBe('');expect(horse.occupant).toBe(b.sessionId);
  });
  it('replicates one rider, blocks foot teleports, supports late join and dismount',async()=>{
    const room=await server.createRoom('world',{});
    const a=await server.connectTo(room,{name:'Alice'}),b=await server.connectTo(room,{name:'Bob'});
    a.onMessage('ride-result',()=>{});b.onMessage('ride-result',()=>{});
    await room.waitForNextPatch();
    const h=room.state.rides.get(HORSE.id)!;
    for(const c of [a,b])Object.assign(room.state.players.get(c.sessionId)!,{x:h.x+1.5,y:h.y,z:h.z});
    a.send('ride-action',{action:'mount'});b.send('ride-action',{action:'mount'});
    await expect.poll(()=>h.occupant).not.toBe('');await room.waitForNextPatch();
    expect([a.sessionId,b.sessionId]).toContain(h.occupant);
    expect([...room.state.players.values()].filter(p=>p.rideId)).toHaveLength(1);
    const driver=h.occupant===a.sessionId?a:b;
    const startX=h.x;
    driver.send('move',{x:200,y:9,z:200,heading:0});await room.waitForMessage('move');
    expect(room.state.players.get(driver.sessionId)!.x).toBeCloseTo(startX);
    driver.send('ride-input',{seq:1,dirX:0,dirZ:1,run:false});await room.waitForMessage('ride-input');
    await expect.poll(()=>h.heading).not.toBe(HORSE.heading);
    const late=await server.connectTo(room,{name:'Carol'});await room.waitForNextPatch();
    expect(late.state.rides.get(HORSE.id).occupant).toBe(driver.sessionId);
    expect(late.state.players.get(driver.sessionId).rideId).toBe(HORSE.id);
    await new Promise(r=>setTimeout(r,350));driver.send('ride-action',{action:'dismount'});
    await expect.poll(()=>h.occupant).toBe('');await room.waitForNextPatch();
    expect(driver.state.players.get(driver.sessionId).rideId).toBe('');
    const p=room.state.players.get(driver.sessionId)!;expect(p.y).toBeLessThan(h.y+.1);
    const before=p.x;driver.send('move',{x:p.x+.1,y:p.y,z:p.z,heading:0});await room.waitForMessage('move');
    expect(p.x).toBeGreaterThan(before);
  });
  it('reserves a disconnected rider seat and restores the same mounted session',async()=>{
    const room=await server.createRoom('world',{}),a=await server.connectTo(room,{name:'Alice'});
    a.onMessage('ride-result',()=>{});await room.waitForNextPatch();
    const h=room.state.rides.get(HORSE.id)!;
    Object.assign(room.state.players.get(a.sessionId)!,{x:h.x+1.5,y:h.y,z:h.z});
    a.send('ride-action',{action:'mount'});await expect.poll(()=>h.occupant).toBe(a.sessionId);await room.waitForNextPatch();
    const token=a.reconnectionToken,id=a.sessionId;await a.leave(false);await expect.poll(()=>room.clients.length).toBe(0);
    expect(h.occupant).toBe(id);expect(h.speed).toBe(0);
    const restored=await server.sdk.reconnect(token);await room.waitForNextPatch();
    expect(restored.sessionId).toBe(id);expect(restored.state.players.get(id).rideId).toBe(HORSE.id);
    await restored.leave(true);await expect.poll(()=>h.occupant).toBe('');
  });
});
